// Лінія Швеця — друга наскрізна лінія, для контрасту з Гнатюком.
//
// Гнатюк — вертикаль: людина зверху, яка може тебе переставити. Швець —
// горизонталь: такий самий, як ти, і саме тому його зрада його й виправдовує.
// Лінія тримається на питанні «чому він здав тебе, хоч міг промовчати»,
// і на тому, що відповідь нічого не змінює для тебе, але змінює його.
//
// Сцени йдуть лише через `next` (див. `nextLineScene` у src/run.ts) і не
// потрапляють у спільний пул. «Гарного» виходу тут немає: обидві розплати гіркі.

import type { Card, CardKind, Condition, Effect, Phase, NextEvent } from '../src/types.ts';

type Stats = NonNullable<Effect['stats']>;

interface OExtra {
  voice?: string;
  flags?: Record<string, boolean>;
  journal?: string;
  next?: NextEvent | NextEvent[];
  skills?: NonNullable<Effect['skills']>;
  requires?: Condition;
  lockedHint?: string;
  outcome?: string;
}

function o(id: string, text: string, stats: Stats, outcome: string, extra: OExtra = {}) {
  return {
    id,
    text,
    ...(extra.next ? { next: extra.next } : {}),
    ...(extra.requires ? { requires: extra.requires } : {}),
    ...(extra.lockedHint ? { lockedHint: extra.lockedHint } : {}),
    effects: {
      stats,
      ...(extra.skills ? { skills: extra.skills } : {}),
      ...(extra.flags ? { flags: extra.flags } : {}),
      ...(extra.journal ? { journal: extra.journal } : {}),
    },
    outcome: { text: outcome, ...(extra.voice ? { voice: extra.voice } : {}) },
  };
}

function c(
  id: string,
  kind: CardKind,
  phase: Phase[],
  text: string,
  options: ReturnType<typeof o>[],
  extra: Partial<Pick<Card, 'follows' | 'after' | 'lead' | 'echo' | 'weight' | 'requires' | 'once' | 'character' | 'tags' | 'voice'>> = {},
): Card {
  return { id, kind, phase, text, options, once: true, ...extra } as Card;
}

