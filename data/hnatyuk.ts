// Лінія Гнатюка — наскрізний персонаж від першого дня до фіналу.
//
// Це не набір сцен, а ланцюг: кожна картка веде в наступну через `next`, і текст
// кожної наступної залежить від того, що саме гравець зробив у попередній.
// Прапорці `hn.*` читаються умовами карток і рядками `echo`, тому «та сама»
// сцена для двох гравців виглядає по-різному.
//
// Що тримає лінію: питання «чому він називає матір на ім'я і чому замовк,
// коли ти згадав Тараса». Відповідь дають сцени 5–7, розплату — 8–9.

import type { Card, CardKind, Condition, Effect, Phase, NextEvent } from '../src/types.ts';

type Stats = NonNullable<Effect['stats']>;

interface OExtra {
  voice?: string;
  flags?: Record<string, boolean>;
  journal?: string;
  next?: NextEvent | NextEvent[];
  skills?: NonNullable<Effect['skills']>;
  requires?: Condition;
  lockedHint?: string;
  outcome?: string;
}

function o(id: string, text: string, stats: Stats, outcome: string, extra: OExtra = {}) {
  return {
    id,
    text,
    ...(extra.next ? { next: extra.next } : {}),
    ...(extra.requires ? { requires: extra.requires } : {}),
    ...(extra.lockedHint ? { lockedHint: extra.lockedHint } : {}),
    effects: {
      stats,
      ...(extra.skills ? { skills: extra.skills } : {}),
      ...(extra.flags ? { flags: extra.flags } : {}),
      ...(extra.journal ? { journal: extra.journal } : {}),
    },
    outcome: { text: outcome, ...(extra.voice ? { voice: extra.voice } : {}) },
  };
}

function c(
  id: string,
  kind: CardKind,
  phase: Phase[],
  text: string,
  options: ReturnType<typeof o>[],
  extra: Partial<Pick<Card, 'follows' | 'lead' | 'echo' | 'weight' | 'requires' | 'once' | 'character' | 'tags' | 'voice'>> = {},
): Card {
  return { id, kind, phase, text, options, once: true, ...extra } as Card;
}

